  function normalize(code) {
    if (!code) return "en";
    var c = String(code).replace("_", "-");
    if (T[c]) return c;
    var lower = c.toLowerCase();
    if (lower === "zh-cn" || lower === "zh-hans" || lower.indexOf("zh-hans") === 0) return "zh-CN";
    if (lower === "zh-tw" || lower === "zh-hant" || lower === "zh-hk" || lower.indexOf("zh-hant") === 0) return "zh-TW";
    if (lower === "pt-br" || lower === "pt") return "pt-BR";
    var base = c.split("-")[0].toLowerCase();
    var map = {
      en: "en", zh: "zh-CN", ja: "ja", ko: "ko", es: "es", fr: "fr", de: "de",
      it: "it", pt: "pt-BR", ru: "ru", ar: "ar", hi: "hi", th: "th", vi: "vi",
      id: "id", tr: "tr", nl: "nl", pl: "pl"
    };
    return map[base] || "en";
  }

